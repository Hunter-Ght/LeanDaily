// 家族 machine（引体向上架、固定器械）的动作数据。格式见 specs_base.js 顶部注释。
// 坐姿用 mode:'seat'（scene.html 家族 machine 区域）：stand + 手掌贴合握把 + 连杆 links + 可选的腿摆动。
// 坐姿 drop 0.45、back 0.4：骨盆在 (0, 0.5, -0.44)，肩在 y≈1.0、z≈-0.465（躯干直立时）。

const rad = d => (d * Math.PI) / 180;

// 座椅 + 靠背 + 底座 + 配重片。tilt 靠背后倾角（躯干 lean 要取 -tilt）。
const seatSet = (o = {}) => {
  const { tilt = 4, backH = 0.62, seatY = 0.39, stackZ = -1.02, noBack = false, gantry = 1.25, gx = 0.45 } = o;
  const th = rad(tilt), c = Math.cos(th), s = Math.sin(th);
  const p0 = [seatY + 0.05, -0.545]; // 靠背贴着骨盆后面的点 (y, z)
  const ctr = (h, off) => [p0[0] + (c * h) / 2 - s * off, p0[1] - (s * h) / 2 - c * off];
  const [by, bz] = ctr(backH, 0.035), [py, pz] = ctr(backH + 0.25, 0.1);
  return [
    { box: [gx * 2 + 0.1, 0.05, 0.86], at: [0, 0.025, -0.58], m: 'frame' },
    { box: [0.4, 0.09, 0.44], at: [0, seatY, -0.33], m: 'pad' },
    { box: [0.1, seatY - 0.07, 0.1], at: [0, (seatY - 0.07) / 2 + 0.05, -0.3], m: 'frame' },
    ...(noBack ? [] : [
      { box: [0.42, backH, 0.07], at: [0, by, bz], rot: [-tilt, 0, 0], m: 'pad' },
      { box: [0.07, backH + 0.25, 0.07], at: [0, py, pz], rot: [-tilt, 0, 0], m: 'frame' },
    ]),
    { box: [0.34, 0.9, 0.14], at: [0, 0.45, stackZ], m: 'stack' },
    { box: [0.4, 0.04, 0.2], at: [0, 0.92, stackZ], m: 'frame' },
    // 机架：两侧立柱 + 顶梁，连杆从立柱上伸出。
    ...(gantry ? [-1, 1].map(k => ({ box: [0.06, gantry, 0.06], at: [k * gx, gantry / 2, -0.95], m: 'frame' }))
      .concat([{ box: [gx * 2 + 0.06, 0.06, 0.06], at: [0, gantry, -0.95], m: 'frame' }]) : []),
  ];
};
// 握把：拳心处沿某个轴的一根短钢杆（axis 'x' | 'y' | 'z'，len 长度，along 沿前臂前移多少，off 世界偏移）。
const grips = (axis = 'x', len = 0.13, along = 0.08, off = [0, 0, 0]) =>
  ['handL', 'handR'].map((f, i) => {
    const k = i ? -1 : 1, h = len / 2;
    const e = { x: [h, 0, 0], y: [0, h, 0], z: [0, 0, h] }[axis];
    const o = [k * off[0], off[1], off[2]];
    return {
      from: { t: f, along, off: [o[0] - e[0], o[1] - e[1], o[2] - e[2]] },
      to: { t: f, along, off: [o[0] + e[0], o[1] + e[1], o[2] + e[2]] },
      r: 0.017, m: 'steel',
    };
  });
// 连杆：从机架固定点到握把（手背后一点）。
const arms = (fromL, off = [0, 0, 0], along = 0.08) => [
  { from: fromL, to: { t: 'handL', along, off }, r: 0.016 },
  { from: [-fromL[0], fromL[1], fromL[2]], to: { t: 'handR', along, off: [-off[0], off[1], off[2]] }, r: 0.016 },
];

